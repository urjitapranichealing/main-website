document.addEventListener('DOMContentLoaded', () => {
  cacheEnglish();

  let saved = 'en';
  try { saved = localStorage.getItem('urjita-lang') || 'en'; } catch (e) {}
  if (saved === 'mr') setLang('mr');

  document.querySelectorAll('.lang-toggle button').forEach(b => {
    b.addEventListener('click', () => setLang(b.dataset.lang));
  });

  document.querySelectorAll('[data-shop-link]').forEach(a => a.setAttribute('href', SHOP_URL));

  wireWhatsApp();

  /* ---- mobile nav ---- */
  const burger = document.getElementById('burger');
  const nav = document.getElementById('nav');
  const scrim = document.getElementById('scrim');

  function closeNav() {
    if (!nav) return;
    nav.classList.remove('open');
    if (burger) burger.classList.remove('open');
    if (scrim) scrim.classList.remove('on');
    document.body.style.overflow = '';
  }

  if (burger && nav) {
    burger.addEventListener('click', () => {
      const open = nav.classList.toggle('open');
      burger.classList.toggle('open', open);
      if (scrim) scrim.classList.toggle('on', open);
      document.body.style.overflow = open ? 'hidden' : '';
    });
    nav.querySelectorAll('a').forEach(a => a.addEventListener('click', closeNav));
    if (scrim) scrim.addEventListener('click', closeNav);
    document.addEventListener('keydown', e => { if (e.key === 'Escape') closeNav(); });
  }

  /* ---- sticky header shadow ---- */
  const header = document.querySelector('.site-header');
  const onScroll = () => header && header.classList.toggle('scrolled', window.scrollY > 20);
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();

  /* ---- scroll reveal + counters ---- */
  const reveals = document.querySelectorAll('.reveal');
  const counters = document.querySelectorAll('[data-count]');

  if ('IntersectionObserver' in window) {
    const io = new IntersectionObserver(entries => {
      entries.forEach(en => {
        if (en.isIntersecting) { en.target.classList.add('in'); io.unobserve(en.target); }
      });
    }, { threshold: 0.1, rootMargin: '0px 0px -50px' });
    reveals.forEach(el => io.observe(el));

    const co = new IntersectionObserver(entries => {
      entries.forEach(en => {
        if (en.isIntersecting) { countUp(en.target); co.unobserve(en.target); }
      });
    }, { threshold: 0.5 });
    counters.forEach(el => co.observe(el));
  } else {
    reveals.forEach(el => el.classList.add('in'));
  }

  /* ---- year ---- */
  const yr = document.getElementById('yr');
  if (yr) yr.textContent = new Date().getFullYear();
});
