const i18nNodes = [];

function cacheEnglish() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    i18nNodes.push({ el, key: el.getAttribute('data-i18n'), en: el.innerHTML });
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.dataset.enPh = el.getAttribute('placeholder') || '';
  });
}

function setLang(lang) {
  const mr = lang === 'mr';
  document.documentElement.lang = mr ? 'mr' : 'en';
  document.body.classList.toggle('lang-mr', mr);

  i18nNodes.forEach(({ el, key, en }) => {
    el.innerHTML = mr ? (MR[key] || en) : en;
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    el.setAttribute('placeholder', mr ? (MR[key] || el.dataset.enPh) : el.dataset.enPh);
  });

  document.querySelectorAll('.lang-toggle button').forEach(b => {
    b.classList.toggle('on', b.dataset.lang === lang);
  });

  try { localStorage.setItem('urjita-lang', lang); } catch (e) {}
}

/* ============================================================
   WHATSAPP
   ============================================================ */
function waLink(msg) {
  return 'https://wa.me/' + WHATSAPP_NUMBER + '?text=' + encodeURIComponent(msg);
}

function wireWhatsApp() {
  document.querySelectorAll('[data-wa]').forEach(el => {
    el.setAttribute('href', waLink(el.getAttribute('data-wa-msg') || 'Hello Urjita!'));
    el.setAttribute('target', '_blank');
    el.setAttribute('rel', 'noopener');
  });

  const btn = document.getElementById('send-wa');
  if (!btn) return;

  btn.addEventListener('click', () => {
    const val = id => (document.getElementById(id) || {}).value || '';
    const name = val('f-name').trim();
    const phone = val('f-phone').trim();

    if (!name || !phone) {
      alert(document.body.classList.contains('lang-mr')
        ? 'कृपया तुमचे नाव आणि मोबाईल क्रमांक भरा.'
        : 'Please add your name and phone number first.');
      return;
    }

    const msg =
      'Hello Kshipra,\n\n' +
      'Name: ' + name + '\n' +
      'Phone: ' + phone + '\n' +
      'Interested in: ' + val('f-interest') + '\n' +
      'Preferred centre: ' + val('f-where') + '\n\n' +
      (val('f-msg').trim() || '(no additional details)');

    window.open(waLink(msg), '_blank', 'noopener');
  });
}

